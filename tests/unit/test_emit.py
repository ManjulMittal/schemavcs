# ============================================================ engine honesty (E-80+)
def test_E80_a_postgres_script_is_wrapped_in_one_transaction(base_schema):
    target = base_schema.evolve().add_col("users", "a", "int").build()

    script = emit(plan(base_schema, target), "postgres")

    assert script.transactional
    assert script.text().startswith("BEGIN;")
    assert script.text().rstrip().endswith("COMMIT;")


def test_E81_a_mysql_script_is_NOT_wrapped(base_schema):
    """Not an omission. MySQL commits each DDL statement implicitly, so a BEGIN
    would imply a rollback guarantee the engine does not provide (D18)."""
    target = base_schema.evolve().add_col("users", "a", "int").build()

    script = emit(plan(base_schema, target), "mysql")

    assert not script.transactional
    assert "BEGIN" not in script.text()
    assert "COMMIT" not in script.text()


def test_E82_a_mysql_script_carries_a_no_rollback_marker(base_schema):
    target = base_schema.evolve().drop_col("users.email").build()

    text = emit(plan(base_schema, target, **LOSSY_OK), "mysql").text()

    assert "NO ROLLBACK" in text


def test_E83_the_marker_sits_at_the_FIRST_irreversible_step(base_schema):
    """One marker at the boundary is actionable: everything above it is recoverable.
    A marker on every destructive line is noise that stops being read."""
    base = (base_schema.evolve().add_col("users", "a", "int")
            .add_col("users", "b", "int").build())
    target = (base.evolve().add_col("users", "safe_one", "text")
              .drop_col("users.a").drop_col("users.b").build())

    script = emit(plan(base, target, **LOSSY_OK), "mysql")

    marked = [i for i, s in enumerate(script.steps) if s.note
              and "NO ROLLBACK" in s.note]
    assert len(marked) == 1, "exactly one marker"
    irreversible = [i for i, s in enumerate(script.steps) if s.irreversible]
    assert marked[0] == min(irreversible)
    assert script.steps[marked[0]].sql.startswith("ALTER TABLE `users` DROP COLUMN")


def test_postgres_does_not_carry_a_no_rollback_marker(base_schema):
    """Because it can roll back. Emitting the warning anyway would train people to
    ignore it."""
    target = base_schema.evolve().drop_col("users.email").build()

    text = emit(plan(base_schema, target, **LOSSY_OK), "postgres").text()

    assert "NO ROLLBACK" not in text


# ============================================================== honest refusals
def test_a_partial_index_is_refused_for_mysql_not_silently_widened(base_schema):
    """Emitting a non-partial index would produce a database that looks right and
    enforces something different -- the worst available outcome."""
    target = base_schema.evolve().add_index("users", "idx", ["email"],
                                            where="email IS NOT NULL").build()

    p = plan(base_schema, target)
    emit(p, "postgres")                       # fine

    with pytest.raises(UnrepresentableError) as e:
        emit(p, "mysql")
    assert "partial index" in str(e.value)
    assert "every row" in str(e.value), "the message must say what would go wrong"


def test_an_unsigned_column_is_refused_for_postgres(base_schema):
    from schemavcs.model.types import ColumnType
    from dataclasses import replace as dc_replace

    t = base_schema.table("users")
    col = dc_replace(t.column("id"), type=ColumnType("int", (), unsigned=True))
    target = dc_replace(base_schema, tables=(dc_replace(
        t, columns=tuple(col if c.id == col.id else c for c in t.columns)),))

    p = plan(base_schema, target, **LOSSY_OK)
    emit(p, "mysql")                          # fine

    with pytest.raises(UnrepresentableError, match="unsigned"):
        emit(p, "postgres")


def test_a_mysql_prefix_index_is_refused_for_postgres(base_schema):
    from schemavcs.model.evolve import IndexSpec

    target = base_schema.evolve().add_index(
        "users", "idx", [IndexSpec(column="email", prefix_length=10)]).build()

    p = plan(base_schema, target)
