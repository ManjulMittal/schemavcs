def test_a_temp_name_step_is_annotated_as_machinery(base_schema):
    """Generated DDL is read by humans. An unexplained `__schemavcs_tmp_1` in a
    migration is alarming; a comment saying why it is there is not."""
    base = (base_schema.evolve().add_col("users", "x", "int")
            .add_col("users", "y", "int").build())
    target = (base.evolve().rename_col("users.x", "__s")
              .rename_col("users.y", "x").rename_col("users.__s", "y").build())

    script = emit(plan(base, target), "postgres")

    noted = [s for s in script.steps if s.note and "temporary name" in s.note]
    assert len(noted) == 2


def test_mysql_refuses_to_index_a_text_column_without_a_prefix_length(base_schema):
    """Discovered by applying generated DDL to a real MySQL server (D38).

    MySQL stores TEXT/BLOB out of line and cannot index it without being told how many
    leading bytes to use. The emitter previously produced `ADD CONSTRAINT ... UNIQUE
    (note)` and the server rejected it -- valid-looking SQL that fails at execution,
    which is exactly the class of bug string assertions cannot catch.
    """
    base = base_schema.evolve().add_col("users", "note", "text").build()
    target = base.evolve().add_index("users", "idx_note", ["note"]).build()

    p = plan(base, target)
    emit(p, "postgres")                        # Postgres indexes TEXT fine

    with pytest.raises(UnrepresentableError) as e:
        emit(p, "mysql")
    assert "prefix length" in str(e.value)
    assert "VARCHAR(n)" in str(e.value), "the message must name a way forward"


def test_mysql_accepts_a_text_index_when_a_prefix_length_is_given(base_schema):
    from schemavcs.model.evolve import IndexSpec

    base = base_schema.evolve().add_col("users", "note", "text").build()
    target = base.evolve().add_index(
        "users", "idx_note", [IndexSpec(column="note", prefix_length=32)]).build()

    stmt = only_statement(base, target, "mysql")

    assert "`note`(32)" in stmt


def test_mysql_refuses_a_unique_constraint_over_a_text_column(base_schema):
    base = base_schema.evolve().add_col("users", "note", "text").build()
    target = base.evolve().add_unique("users", "uq_note", ["note"]).build()

    with pytest.raises(UnrepresentableError, match="TEXT"):
        emit(plan(base, target), "mysql")


# ------------------------------------------------------------------ D48: unknown types
def test_E90_an_unknown_type_is_refused_rather_than_passed_through(base_schema):
    """The model is permissive about type names on purpose (D6) and knows nothing about
    dialects (D5), so a typo reaches the emitter intact. Before this, `TYPES.get(base,
    base)` passed it through and produced `ALTER COLUMN "x" TYPE somethign` -- DDL that
    parses here and fails on the server, which is the failure mode D39 exists to prevent.
    """
    from schemavcs.dialects import emit
    from schemavcs.engine.plan import plan
    from schemavcs.dialects.emit import UnrepresentableError

    target = base_schema.evolve().retype_col("users.email", "somethign").build()

    with pytest.raises(UnrepresentableError) as e:
        emit(plan(base_schema, target, acknowledge_lossy=True), "postgres")

    assert "somethign" in str(e.value)
    assert "varchar" in str(e.value), "the message must list what IS available"


@pytest.mark.parametrize("dialect,type_name", [
    ("postgres", "blob"),      # MySQL has it, Postgres does not
    ("mysql", "jsonb"),        # and the other way round
    ("mysql", "uuid"),
])
def test_E91_a_type_one_engine_lacks_is_refused_for_that_engine(base_schema, dialect,
                                                               type_name):
    """Not every unknown type is a typo. Some are real types the *other* engine has,
    which is the case most likely to bite: the schema was authored against Postgres and
    someone asks for MySQL."""
    from schemavcs.dialects import emit
    from schemavcs.engine.plan import plan
    from schemavcs.dialects.emit import UnrepresentableError

    target = base_schema.evolve().retype_col("users.email", type_name).build()
    p = plan(base_schema, target, acknowledge_lossy=True)

    with pytest.raises(UnrepresentableError, match=type_name):
        emit(p, dialect)


def test_E92_mysql_refuses_an_unbounded_varchar(base_schema):
    """Postgres reads a bare `varchar` as unbounded and MySQL rejects the statement, so
    a schema authored on one and emitted for the other produced DDL that would not run.
    Same family as E-90: the neutral model can hold it, this engine cannot express it.
    """
    from schemavcs.dialects import emit
    from schemavcs.dialects.emit import UnrepresentableError
    from schemavcs.engine.plan import plan

    target = base_schema.evolve().retype_col("users.email", "varchar").build()
    p = plan(base_schema, target, acknowledge_lossy=True)

    emit(p, "postgres")                       # legal there, and stays legal

    with pytest.raises(UnrepresentableError, match="unbounded"):
        emit(p, "mysql")
