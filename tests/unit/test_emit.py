"""Operation -> SQL, both dialects (E-01..E-10, E-80..E-83).

These tests are about *text*, and deliberately about the places where the two engines
disagree rather than about every character of every statement. Asserting on whole SQL
strings makes tests that break on whitespace and pass on semantics, which is exactly
backwards. The strings are verified for real in the live-execution suite; here the
subject is divergence.
"""
import pytest

from schemavcs.dialects import UnrepresentableError, emit
from schemavcs.engine.plan import plan
from schemavcs.model import schema

BOTH = ["postgres", "mysql"]
LOSSY_OK = dict(acknowledge_lossy=True)


def sql_for(base, target, dialect, **kw):
    return emit(plan(base, target, **kw), dialect).text()


def only_statement(base, target, dialect, **kw):
    script = emit(plan(base, target, **kw), dialect)
    assert len(script) == 1, script.statements
    return script.statements[0]


# ================================================================== happy path
def test_E01_create_table_covers_every_supported_construct():
    base = schema().build()
    target = (schema().table("t")
              .col("id", "bigint", pk=True, autoincrement=True)
              .col("name", "varchar(100)", nullable=False)
              .col("note", "text", default="''")
              .unique("uq_name", ["name"])
              .check("ck_note", "note <> ''")
              .build())

    pg = sql_for(base, target, "postgres")

    assert 'CREATE TABLE "t"' in pg
    assert '"id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY' in pg
    assert '"name" varchar(100) NOT NULL' in pg
    assert """"note" text DEFAULT ''""" in pg
    assert 'CONSTRAINT "pk_t" PRIMARY KEY ("id")' in pg
    assert 'CONSTRAINT "uq_name" UNIQUE ("name")' in pg
    assert """CONSTRAINT "ck_note" CHECK (note <> '')""" in pg


def test_E01b_mysql_uses_its_own_identifiers_and_identity_syntax():
    base = schema().build()
    target = schema().table("t").col("id", "bigint", pk=True,
                                     autoincrement=True).build()

    my = sql_for(base, target, "mysql")

    assert "CREATE TABLE `t`" in my
    assert "`id` bigint NOT NULL AUTO_INCREMENT" in my


@pytest.mark.parametrize("dialect", BOTH)
def test_E02_drop_table(base_schema, dialect):
    target = base_schema.evolve().drop_table("users").build()

    stmt = only_statement(base_schema, target, dialect, **LOSSY_OK)

    assert stmt.startswith("DROP TABLE") and "users" in stmt


