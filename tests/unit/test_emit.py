def test_E09_create_and_drop_index_live_in_different_namespaces(base_schema):
    with_idx = base_schema.evolve().add_index("users", "idx", ["email"]).build()
    assert "CREATE INDEX" in only_statement(base_schema, with_idx, "postgres")

    dropped = with_idx.evolve().drop_index("users.idx").build()
    assert only_statement(with_idx, dropped, "postgres") == 'DROP INDEX "idx";'
    assert "ALTER TABLE `users` DROP INDEX" in only_statement(with_idx, dropped,
                                                             "mysql")


